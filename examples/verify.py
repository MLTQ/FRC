"""Generate quantified vacuum/diffusion convergence and experiment sensitivity."""
from dataclasses import replace
from pathlib import Path
import json
import numpy as np
from scipy.constants import mu_0
from scipy.special import j1, jn_zeros
from plasma_bench.geometry import Grid
from plasma_bench.config import Experiment
from plasma_bench.electromagnetics import loop_field
from plasma_bench.numerics import field_from_flux, cell_divergence
from plasma_bench.plasma import StationaryDiffusion
from plasma_bench.experiments import comparison_config
from plasma_bench.simulation import run


def vacuum_metrics():
    rows = []
    for n in (21, 41, 81):
        g = Grid(.04, .1, n, 2*n-1)
        p, br, bz = loop_field(*g.mesh, .07)
        _, bzh = field_from_flux(g, p)
        error = np.max(abs(bzh[2:-2, 2:-2]-bz[2:-2, 2:-2]))/np.max(abs(bz))
        rows.append({"nr": n, "nz": 2*n-1, "relative_Bz_max_error": float(error),
                     "face_divergence_t_m": float(np.max(abs(cell_divergence(g, p))))})
    return rows


def eigenmode_metrics():
    rows = []
    sigma = 2e4
    for n in (17, 33, 65):
        g = Grid(.05, .1, n, 2*n-1)
        r, z = g.mesh
        kr = jn_zeros(1, 1)[0]/g.radius
        lam = (kr**2+(np.pi/(2*g.half_length))**2)/(mu_0*sigma)
        p = r*j1(kr*r)*np.cos(np.pi*z/(2*g.half_length))
        p[[0, -1]] = 0; p[:, [0, -1]] = 0
        dt = .2/lam/100
        solver = StationaryDiffusion(g, sigma, np.zeros(g.shape), p)
        for _ in range(100):
            state = solver.step(np.zeros(g.shape), dt)
        expected = p*(1+dt*lam)**-100
        rows.append({"nr": n, "relative_L2_error_at_fixed_BE_time": float(np.linalg.norm(state.induced_psi-expected)/np.linalg.norm(expected))})
    temporal = []
    for steps in (5, 10, 20, 40):
        solver = StationaryDiffusion(g, sigma, np.zeros(g.shape), p)
        for _ in range(steps):
            state = solver.step(np.zeros(g.shape), .5/lam/steps)
        temporal.append({"steps": steps, "relative_L2_error_vs_continuous_decay": float(np.linalg.norm(state.induced_psi-p*np.exp(-.5))/np.linalg.norm(p*np.exp(-.5)))})
    return rows, temporal


def experiment_sensitivity():
    base = comparison_config("rlc", base=replace(Experiment(), output_stride=20))
    variations = {
        "reference": base,
        "half_dt": replace(base, dt=base.dt/2),
        "quarter_dt": replace(base, dt=base.dt/4),
        "coarse_mesh": replace(base, grid=Grid(.15, .3, 31, 61)),
        "fine_mesh": replace(base, grid=Grid(.15, .3, 121, 241)),
        "outer_1.5x": replace(base, grid=Grid(.225, .45, 91, 181)),
        "outer_2x": replace(base, grid=Grid(.30, .60, 121, 241)),
    }
    rows, reference = [], None
    for name, config in variations.items():
        print("Verifying", name, flush=True)
        result = run(config, topology=False)
        a, s = result.arrays, result.metadata["summary"]
        if reference is None:
            reference = result
        ref = np.interp(a["times"], reference.arrays["times"], reference.arrays["center_bz"])
        delta = np.max(abs(a["center_bz"]-ref))/np.max(abs(ref))
        rows.append({"case": name, "nr": config.grid.nr, "nz": config.grid.nz,
                     "dt_s": float(np.diff(a["times"])[0]),
                     "center_trace_max_change_vs_reference": float(delta),
                     "minimum_axis_bz_t": s["minimum_axis_bz_t"],
                     "minimum_bz_over_bias": s["min_bz_over_bias"],
                     "peak_j_theta_a_m2": s["peak_j_theta_a_m2"],
                     "ohmic_heat_j": s["ohmic_heat_j"],
                     "numerical_loss_j": s["numerical_loss_j"],
                     "energy_balance_relative_error": s["energy_balance_relative_error"]})
    return rows


def main():
    vacuum = vacuum_metrics()
    space, time = eigenmode_metrics()
    sensitivity = experiment_sensitivity()
    out = Path("outputs/verification")
    out.mkdir(parents=True, exist_ok=True)
    (out/"metrics.json").write_text(json.dumps({"vacuum": vacuum, "diffusion_space": space,
                                               "diffusion_time": time, "experiment_sensitivity": sensitivity}, indent=2)+"\n")
    lines = ["# Verification measurements", "", "Generated by `python -m examples.verify`. Test suite separately covers independent",
             "Biot–Savart quadrature, flux integration, Faraday law, serialization, topology,",
             "passive energy decay and exact mixed vacuum/conductor current constraints.", "",
             "## Vacuum reconstruction", "", "| Mesh | Max Bz error / peak Bz | Face divergence [T/m] |", "|---|---:|---:|"]
    for row in vacuum:
        lines.append(f"| {row['nr']} × {row['nz']} | {row['relative_Bz_max_error']:.4g} | {row['face_divergence_t_m']:.3g} |")
    order = np.log2(vacuum[-2]["relative_Bz_max_error"]/vacuum[-1]["relative_Bz_max_error"])
    lines += ["", f"Observed final refinement order: **{order:.3f}**. This is nodal reconstruction error;",
              "the analytic loop field itself is tested independently against quadrature.", "",
              "## Diffusion eigenmode", "", "The analytic mode is `r J1(kr r) cos(pi z/(2 Z))` with `J1(kr R)=0`.",
              "Space errors compare to exact backward-Euler modal decay, isolating spatial error.", "",
              "| Radial nodes | Relative L2 spatial error |", "|---|---:|"]
    for row in space:
        lines.append(f"| {row['nr']} | {row['relative_L2_error_at_fixed_BE_time']:.4g} |")
    lines += ["", "| Time steps to 0.5 decay times | Relative L2 error vs continuous solution |", "|---|---:|"]
    for row in time:
        lines.append(f"| {row['steps']} | {row['relative_L2_error_vs_continuous_decay']:.4g} |")
    lines += ["", "## RLC experiment sensitivity", "", "Same normalized source, plasma and duration in every row. Outer-domain tests keep",
              "dr and dz fixed. Mesh changes also move the effective node-sampled material interface;",
              "these are practical sensitivity measurements, not a claim of smooth second-order convergence.", "",
              "| Case | Mesh | dt [µs] | Center trace change | Min on-axis Bz [mT] | Ohmic heat [J] | Numerical loss [J] |", "|---|---|---:|---:|---:|---:|---:|"]
    for row in sensitivity:
        lines.append(f"| {row['case']} | {row['nr']}×{row['nz']} | {row['dt_s']*1e6:g} | {row['center_trace_max_change_vs_reference']:.2%} | {row['minimum_axis_bz_t']*1e3:.4g} | {row['ohmic_heat_j']:.4g} | {row['numerical_loss_j']:.4g} |")
    lines += ["", "Numerical loss decreases with dt; a tiny algebraic energy residual alone does not",
              "establish physical or time-discretization accuracy. Near-threshold axis reversal",
              "and closed-flux lifetime require more stringent convergence than large probe signals.", "",
              "Uniform-conductivity eigenmode boundaries are manufactured verification boundaries,",
              "not a substitute for checking the finite exterior boundary used by experiments."]
    Path("docs/VERIFICATION.md").write_text("\n".join(lines)+"\n")
    topology_rows = []
    for kind in ("rlc", "burst"):
        config = comparison_config(kind, base=replace(Experiment(), grid=Grid(.15, .3, 121, 241), dt=.125e-6, output_stride=8))
        print("Checking refined topology", kind, flush=True)
        result = run(config)
        topology_rows.append({"waveform": kind, "configuration": config.to_dict(), "summary": result.metadata["summary"]})
    (out/"topology_refinement.json").write_text(json.dumps(topology_rows, indent=2)+"\n")
    with Path("docs/VERIFICATION.md").open("a") as report:
        report.write("\n## Joint mesh/time refinement of topology\n\n121×241 mesh, dt=0.125 µs, topology snapshots every 1 µs. Same finite outer boundary.\n\n")
        for row in topology_rows:
            s = row["summary"]
            report.write(f"- {row['waveform']}: {s['classification']}; sampled lifetime lower bound {s['closed_flux_lifetime_lower_bound_s']*1e6:.2f} µs; minimum axis Bz {s['minimum_axis_bz_t']*1e3:.3f} mT.\n")
        report.write("\nThis is a sensitivity check, not converged physical validation of the topology duration.\n")


if __name__ == "__main__":
    main()
