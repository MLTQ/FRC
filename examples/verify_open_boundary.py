def verify(directory="outputs/open_boundary_verification"):
    directory = Path(directory); directory.mkdir(parents=True, exist_ok=True)
    metrics = all_measurements(); metrics["provenance"] = provenance()
    (directory/"metrics.json").write_text(json.dumps(metrics, indent=2, allow_nan=False)+"\n")
    plot(metrics, directory/"open_boundary.png"); report(metrics)
    return metrics


if __name__ == "__main__":
    verify()
