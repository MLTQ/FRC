"""Measured infinite-exterior accuracy and coil-pulse boundary sensitivity."""
from pathlib import Path
import hashlib
import importlib.metadata
import json
import platform
from .open_measurements import all_measurements


def provenance():
    digest = hashlib.sha256()
    paths = sorted(Path("plasma_bench").glob("*.py"))+[Path("examples/coupled_measurements.py"), Path("examples/open_measurements.py"), Path(__file__)]
    for path in paths:
        digest.update(path.name.encode()); digest.update(path.read_bytes())
    return {"source_sha256": digest.hexdigest(), "python": platform.python_version(), "platform": platform.platform(),
            "versions": {k: importlib.metadata.version(k) for k in ("numpy", "scipy", "matplotlib")},
            "method": "variational decaying magnetic multipoles plus symmetric finite interior energy; midpoint gas/field work",
            "initial_gas": {"density_kg_m3": 1., "pressure_pa": 1., "velocity_m_s": [0., 0.]},
            "boundaries": "fixed reflecting gas chamber; analytic induced magnetic exterior to infinity or fixed comparison",
            "interpretation": "open magnetic-boundary verification, not free fluid-interface or formation validation"}


def select(metrics, *, cells=16, extent=None, boundary="multipole", modes=12, cfl=.2):
    return [r for r in metrics["pulse"] if r["radial_cells"] == cells and (extent is None or r["extent"] == extent)
            and r["boundary"] == boundary and r["modes"] == modes and r["configuration"]["parameters"]["cfl"] == cfl]


def plot(metrics, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.ticker import NullFormatter
    from plasma_bench.visualization import STYLE
    with plt.rc_context(STYLE):
        fig, axes = plt.subplots(2, 2, figsize=(12, 8), layout="constrained")
        rows = metrics["static"]["spatial"]
        for key, label, color in (("relative_interior_flux_L2", "Interior flux vs loop integral", "#72ddc4"),
                                  ("relative_normal_derivative_jump", "Interface derivative mismatch", "#ffcc75")):
            axes[0, 0].loglog([r["radial_fluid_cells"] for r in rows], [r[key] for r in rows], "o-", color=color, label=label)
        axes[0, 0].set(title="Asymmetric current · spatial convergence", xlabel="Radial fluid cells", ylabel="Relative L2 error")
        rows = metrics["static"]["modal"]
        axes[0, 1].semilogy([r["modes"] for r in rows], [r["relative_exterior_B_L2"] for r in rows], "o-", color="#aa9cfc", label="Exterior B vs independent loop integral")
        axes[0, 1].set(title="Modal refinement reaches spatial-error limit", xlabel="Retained multipoles", ylabel="Exterior magnetic-field relative L2 error")
        for boundary, label, color in (("fixed", "Zero induced flux at outer wall", "#f687a6"), ("multipole", "Decaying exterior to infinity", "#72ddc4")):
            rows = select(metrics, boundary=boundary)
            axes[1, 0].plot([r["extent"] for r in rows], [r["diagnostics"]["source_work_j"] for r in rows], "o-", color=color, label=label)
        axes[1, 0].set(title="Same plasma and coils · 16 × 32 fluid cells", xlabel="Matching surface radius / half-length [m]", ylabel="Final applied-field work [J]")
        rows = [r for r in metrics["pulse"] if r["boundary"] == "multipole" and r["extent"] == 2 and r["modes"] == 12 and r["configuration"]["parameters"]["cfl"] == .2]
        axes[1, 1].plot([r["radial_cells"] for r in rows], [r["diagnostics"]["maximum_speed_m_s"] for r in rows], "o-", color="#ffcc75", label="Open-boundary maximum final speed")
        axes[1, 1].set(title="Remaining task: resolve driven plasma flow", xlabel="Radial cells", ylabel="Maximum speed [m/s]")
        axes[0, 0].set_xticks([8, 16, 32, 64], labels=["8", "16", "32", "64"])
        axes[0, 0].xaxis.set_minor_formatter(NullFormatter())
        for ax in axes.flat:
            ax.grid(alpha=.2); ax.legend(fontsize=8, labelcolor="#c9d5e5")
        fig.suptitle("MAGNETIC VACUUM TO INFINITY\nExterior energy included · boundary sensitivity removed within measured error", fontsize=15, weight="bold")
        fig.savefig(path, dpi=160); plt.close(fig)


